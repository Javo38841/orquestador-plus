import { contextBridge, ipcRenderer } from 'electron';
import { IpcChannel, WIKI_CHANGED_EVENT, type OrquestadorApi } from '../shared/ipc';

const api: OrquestadorApi = {
  getAppInfo: () => ipcRenderer.invoke(IpcChannel.getAppInfo),
  captureInbox: (text) => ipcRenderer.invoke(IpcChannel.captureInbox, text),
  listInbox: () => ipcRenderer.invoke(IpcChannel.listInbox),
  convertInboxItem: (id, input) => ipcRenderer.invoke(IpcChannel.convertInboxItem, id, input),
  discardInboxItem: (id) => ipcRenderer.invoke(IpcChannel.discardInboxItem, id),
  listTasks: () => ipcRenderer.invoke(IpcChannel.listTasks),
  createTask: (input) => ipcRenderer.invoke(IpcChannel.createTask, input),
  updateTask: (id, input) => ipcRenderer.invoke(IpcChannel.updateTask, id, input),
  setTaskStatus: (id, status) => ipcRenderer.invoke(IpcChannel.setTaskStatus, id, status),
  setTaskForToday: (id, forToday) => ipcRenderer.invoke(IpcChannel.setTaskForToday, id, forToday),
  deleteTask: (id) => ipcRenderer.invoke(IpcChannel.deleteTask, id),
  hideFromToday: (ids) => ipcRenderer.invoke(IpcChannel.hideFromToday, ids),
  deleteSeries: (id) => ipcRenderer.invoke(IpcChannel.deleteSeries, id),
  listTags: () => ipcRenderer.invoke(IpcChannel.listTags),
  listProjects: () => ipcRenderer.invoke(IpcChannel.listProjects),
  createProject: (name) => ipcRenderer.invoke(IpcChannel.createProject, name),
  deleteProject: (id) => ipcRenderer.invoke(IpcChannel.deleteProject, id),
  listNotes: (section) => ipcRenderer.invoke(IpcChannel.listNotes, section),
  listSections: () => ipcRenderer.invoke(IpcChannel.listSections),
  createSection: (input) => ipcRenderer.invoke(IpcChannel.createSection, input),
  listSkippedFiles: () => ipcRenderer.invoke(IpcChannel.listSkippedFiles),
  openWikiFolder: () => ipcRenderer.invoke(IpcChannel.openWikiFolder),
  onWikiChanged: (listener) => {
    const handler = (): void => listener();
    ipcRenderer.on(WIKI_CHANGED_EVENT, handler);
    return () => ipcRenderer.removeListener(WIKI_CHANGED_EVENT, handler);
  },
  getNote: (slug) => ipcRenderer.invoke(IpcChannel.getNote, slug),
  createNote: (input) => ipcRenderer.invoke(IpcChannel.createNote, input),
  updateNote: (slug, input) => ipcRenderer.invoke(IpcChannel.updateNote, slug, input),
  moveNote: (slug, section) => ipcRenderer.invoke(IpcChannel.moveNote, slug, section),
  deleteNote: (slug, deleteAttachments) =>
    ipcRenderer.invoke(IpcChannel.deleteNote, slug, deleteAttachments),
  attachFile: (input) => ipcRenderer.invoke(IpcChannel.attachFile, input),
  readAttachment: (slug, src) => ipcRenderer.invoke(IpcChannel.readAttachment, slug, src),
  openAttachment: (slug, src) => ipcRenderer.invoke(IpcChannel.openAttachment, slug, src),
  listBugs: () => ipcRenderer.invoke(IpcChannel.listBugs),
  createBug: (input) => ipcRenderer.invoke(IpcChannel.createBug, input),
  updateBug: (id, input) => ipcRenderer.invoke(IpcChannel.updateBug, id, input),
  setBugStatus: (id, status) => ipcRenderer.invoke(IpcChannel.setBugStatus, id, status),
  deleteBug: (id) => ipcRenderer.invoke(IpcChannel.deleteBug, id),
  listSnippets: () => ipcRenderer.invoke(IpcChannel.listSnippets),
  createSnippet: (input) => ipcRenderer.invoke(IpcChannel.createSnippet, input),
  updateSnippet: (id, input) => ipcRenderer.invoke(IpcChannel.updateSnippet, id, input),
  deleteSnippet: (id) => ipcRenderer.invoke(IpcChannel.deleteSnippet, id),
  copyToClipboard: (text) => ipcRenderer.invoke(IpcChannel.copyToClipboard, text),
  listTopics: () => ipcRenderer.invoke(IpcChannel.listTopics),
  createTopic: (input) => ipcRenderer.invoke(IpcChannel.createTopic, input),
  updateTopic: (id, input) => ipcRenderer.invoke(IpcChannel.updateTopic, id, input),
  setTopicStatus: (id, status) => ipcRenderer.invoke(IpcChannel.setTopicStatus, id, status),
  deleteTopic: (id) => ipcRenderer.invoke(IpcChannel.deleteTopic, id),
  listJournal: () => ipcRenderer.invoke(IpcChannel.listJournal),
  saveJournalEntry: (date, text) => ipcRenderer.invoke(IpcChannel.saveJournalEntry, date, text),
  search: (text) => ipcRenderer.invoke(IpcChannel.search, text),
  getPortalStatus: () => ipcRenderer.invoke(IpcChannel.getPortalStatus),
  setPortalEnabled: (enabled) => ipcRenderer.invoke(IpcChannel.setPortalEnabled, enabled),
  listPortalLinks: () => ipcRenderer.invoke(IpcChannel.listPortalLinks),
  createPortalLink: (input) => ipcRenderer.invoke(IpcChannel.createPortalLink, input),
  revokePortalLink: (id) => ipcRenderer.invoke(IpcChannel.revokePortalLink, id),
  getRemindersEnabled: () => ipcRenderer.invoke(IpcChannel.getRemindersEnabled),
  setRemindersEnabled: (enabled) => ipcRenderer.invoke(IpcChannel.setRemindersEnabled, enabled),
  getBoardProject: () => ipcRenderer.invoke(IpcChannel.getBoardProject),
  setBoardProject: (projectId) => ipcRenderer.invoke(IpcChannel.setBoardProject, projectId),
  getBoardPanelOpen: () => ipcRenderer.invoke(IpcChannel.getBoardPanelOpen),
  setBoardPanelOpen: (open) => ipcRenderer.invoke(IpcChannel.setBoardPanelOpen, open),
  getSnippetsView: () => ipcRenderer.invoke(IpcChannel.getSnippetsView),
  setSnippetsView: (view) => ipcRenderer.invoke(IpcChannel.setSnippetsView, view),
  getFocusMinutes: () => ipcRenderer.invoke(IpcChannel.getFocusMinutes),
  setFocusMinutes: (minutes) => ipcRenderer.invoke(IpcChannel.setFocusMinutes, minutes),
  exportAll: () => ipcRenderer.invoke(IpcChannel.exportAll),
};

contextBridge.exposeInMainWorld('orquestador', api);
